def test_security_headers_present_not_flagged():
    fp = fingerprint_response("t.com", 200, {
        "Server": "nginx",
        "Strict-Transport-Security": "max-age=31536000",
        "Content-Security-Policy": "default-src 'self'; frame-ancestors 'none'",
        "X-Content-Type-Options": "nosniff",
        "X-Frame-Options": "DENY",
        "Referrer-Policy": "no-referrer",
    }, b"")
    for v in ("missing-hsts", "missing-csp", "clickjacking", "mime-sniffing"):
        assert v not in fp.vuln_classes
    assert "strict-transport-security" in fp.security_headers


